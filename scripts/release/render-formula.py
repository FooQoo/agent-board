#!/usr/bin/env python3
"""Render the Homebrew Formula for one published Agent Board release.

Usage:
  render-formula.py --tag v1.0.0 --sums SHA256SUMS [--assets DIR] [--out FILE]
  render-formula.py --self-test

The Formula is built from three inputs only: the release tag, the Release
SHA256SUMS, and (optionally) the archives themselves. Both per-CPU archives
must be listed once, with the version of the tag; with --assets every listed
archive must exist and hash to its listed value. Anything else is refused and
no output file is written. URLs always point at the same tagged Release of
FooQoo/agent-board, never at "latest", and the same inputs give the same text.

The script only writes the file named by --out (or stdout). It never contacts
the network or the Tap; submitting the Formula is a separate, manual step.
"""
import argparse
import hashlib
import os
import re
import sys
import tempfile
from pathlib import Path

REPO_URL = "https://github.com/FooQoo/agent-board"
TARGETS = {"arm": "aarch64-apple-darwin", "intel": "x86_64-apple-darwin"}
TAG = re.compile(r"^v(\d+\.\d+\.\d+)$")
SUM_LINE = re.compile(r"^([0-9a-f]{64}) [ *](\S+)$")
ARCHIVE = re.compile(r"^agboard-(\d+\.\d+\.\d+)-([a-z0-9_]+-apple-darwin)\.tar\.gz$")
DESC = "Local, history-backed work board for users and AI agents"

TEMPLATE = """\
# Generated by scripts/release/render-formula.py from the {tag} release assets.
# Do not edit by hand: render it again from the published SHA256SUMS.
class Agboard < Formula
  desc "{desc}"
  homepage "{repo}"
  license "MIT"

  depends_on macos: :sequoia

  on_macos do
    on_arm do
      url "{arm_url}"
      sha256 "{arm_sha}"
    end

    on_intel do
      url "{intel_url}"
      sha256 "{intel_sha}"
    end
  end

  def install
    # The archive holds the signed binary as shipped. Install it untouched:
    # no strip, install_name_tool, lipo or re-signing here.
    bin.install "agboard"
    pkgshare.install "LICENSE", "THIRD_PARTY_NOTICES.txt"
  end

  test do
    assert_match version.to_s, shell_output("#{{bin}}/agboard --version")
    assert_operator (pkgshare/"LICENSE").size, :>, 0
    assert_operator (pkgshare/"THIRD_PARTY_NOTICES.txt").size, :>, 0

    # Only temporary data: the board lives under testpath.
    ENV["AGBOARD_HOME"] = (testpath/"agboard-home").to_s
    (testpath/"work").mkpath
    cd testpath/"work" do
      system bin/"agboard", "project", "create", "Formula Test"
      assert_match "No tasks to pick up.", shell_output("#{{bin}}/agboard progress")
    end
  end
end
"""


class RenderError(Exception):
    pass


def parse_sums(text, version):
    """Return {target: sha256} for exactly the two archives of `version`."""
    found = {}
    for number, line in enumerate(text.splitlines(), 1):
        if not line.strip():
            continue
        match = SUM_LINE.match(line)
        if not match:
            raise RenderError(f"SHA256SUMS line {number} is not '<64 lowercase hex>  <file>': {line!r}")
        sha, name = match.groups()
        archive = ARCHIVE.match(name)
        if not archive:
            raise RenderError(f"SHA256SUMS lists an unexpected file: {name}")
        if archive.group(1) != version:
            raise RenderError(f"{name} is version {archive.group(1)}, but the tag is v{version}")
        if name in found:
            raise RenderError(f"SHA256SUMS lists {name} twice")
        found[name] = sha
    wanted = {f"agboard-{version}-{target}.tar.gz" for target in TARGETS.values()}
    missing = sorted(wanted - set(found))
    if missing:
        raise RenderError(f"SHA256SUMS lacks {', '.join(missing)}")
    extra = sorted(set(found) - wanted)
    if extra:
        raise RenderError(f"SHA256SUMS lists unsupported targets: {', '.join(extra)}")
    return found


def check_assets(directory, found):
    for name, sha in sorted(found.items()):
        path = Path(directory) / name
        if not path.is_file():
            raise RenderError(f"archive {path} is missing")
        actual = hashlib.sha256(path.read_bytes()).hexdigest()
        if actual != sha:
            raise RenderError(f"{name} hashes to {actual}, which does not match SHA256SUMS ({sha})")


def render(tag, sums_text, assets=None, repo_url=REPO_URL):
    if repo_url != REPO_URL:
        raise RenderError(f"release URL base must be {REPO_URL}, got {repo_url!r}")
    match = TAG.match(tag)
    if not match:
        raise RenderError(f"tag {tag!r} is not of the form vMAJOR.MINOR.PATCH")
    version = match.group(1)
    found = parse_sums(sums_text, version)
    if assets is not None:
        check_assets(assets, found)
    values = {"tag": tag, "desc": DESC, "repo": repo_url}
    for key, target in TARGETS.items():
        name = f"agboard-{version}-{target}.tar.gz"
        values[f"{key}_url"] = f"{repo_url}/releases/download/{tag}/{name}"
        values[f"{key}_sha"] = found[name]
    return TEMPLATE.format(**values)


def write_atomic(path, text):
    path = Path(path)
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=".render-formula-")
    try:
        # mkstemp creates the file as 0600; `brew style` refuses a Formula
        # that is not readable by everyone.
        os.fchmod(fd, 0o644)
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(text)
        os.replace(tmp, path)
    except BaseException:
        os.unlink(tmp)
        raise


def self_test():
    root = Path(__file__).resolve().parents[2]
    fixtures = root / "tests" / "fixtures" / "release"
    sums = (fixtures / "SHA256SUMS").read_text(encoding="utf-8")
    expected = (fixtures / "agboard.rb.expected").read_text(encoding="utf-8")
    lines = sums.splitlines()
    arm, intel = lines
    sha = "0" * 64
    failures = []

    def expect(label, condition):
        if not condition:
            failures.append(label)

    def refused(label, tag, text, reason, **kwargs):
        try:
            render(tag, text, **kwargs)
        except RenderError as error:
            expect(f"{label}: message {error} lacks {reason!r}", reason in str(error))
        else:
            failures.append(f"{label}: was accepted")

    got = render("v1.0.0", sums)
    expect("fixture render equals agboard.rb.expected", got == expected)
    expect("render is repeatable", got == render("v1.0.0", sums))
    expect("no latest URL", "latest" not in got)
    expect("order of lines does not matter", got == render("v1.0.0", intel + "\n" + arm + "\n"))
    refused("missing intel", "v1.0.0", arm + "\n", "lacks agboard-1.0.0-x86_64-apple-darwin")
    refused("missing arm", "v1.0.0", intel + "\n", "lacks agboard-1.0.0-aarch64-apple-darwin")
    refused("empty sums", "v1.0.0", "", "lacks")
    refused("other version", "v1.0.1", sums, "is version 1.0.0, but the tag is v1.0.1")
    refused("mixed versions", "v1.0.0", arm + "\n" + intel.replace("1.0.0", "1.0.1") + "\n", "but the tag is v1.0.0")
    refused("bad tag", "1.0.0", sums, "not of the form")
    refused("prerelease tag", "v1.0.0-rc1", sums, "not of the form")
    refused("short hash", "v1.0.0", arm.replace(arm[:1], "", 1) + "\n" + intel + "\n", "not '<64 lowercase hex>")
    refused("uppercase hash", "v1.0.0", arm.upper().replace("AGBOARD", "agboard").replace(".TAR.GZ", ".tar.gz").replace("APPLE-DARWIN", "apple-darwin") + "\n" + intel + "\n", "not '<64 lowercase hex>")
    refused("duplicate", "v1.0.0", arm + "\n" + arm + "\n" + intel + "\n", "twice")
    refused("unknown file", "v1.0.0", sums + f"{sha}  agboard-1.0.0-x86_64-unknown-linux-gnu.tar.gz\n", "unexpected file")
    refused("extra target", "v1.0.0", sums + f"{sha}  agboard-1.0.0-riscv64-apple-darwin.tar.gz\n", "unsupported targets")
    refused("bad url base", "v1.0.0", sums, "release URL base must be", repo_url="https://example.com/FooQoo/agent-board")
    refused("latest url base", "v1.0.0", sums, "release URL base must be", repo_url=REPO_URL + "/releases/latest")

    with tempfile.TemporaryDirectory() as directory:
        names = [line.split()[1] for line in lines]
        refused("assets missing", "v1.0.0", sums, "is missing", assets=directory)
        for name, data in zip(names, (b"fixture aarch64 archive", b"fixture x86_64 archive")):
            (Path(directory) / name).write_bytes(data)
        expect("assets matching the sums render", render("v1.0.0", sums, assets=directory) == expected)
        (Path(directory) / names[1]).write_bytes(b"tampered")
        refused("hash mismatch", "v1.0.0", sums, "does not match SHA256SUMS", assets=directory)

    if failures:
        for failure in failures:
            print(f"render-formula self-test FAILED: {failure}", file=sys.stderr)
        sys.exit(1)
    print("render-formula self-test: ok")


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--tag", help="release tag, e.g. v1.0.0")
    parser.add_argument("--sums", help="path to the Release SHA256SUMS file")
    parser.add_argument("--assets", help="directory with the archives, to verify each hash")
    parser.add_argument("--out", help="write the Formula here instead of stdout")
    parser.add_argument("--self-test", action="store_true", help="run the built-in refusal and fixture cases")
    args = parser.parse_args()
    if args.self_test:
        self_test()
        return
    if not args.tag or not args.sums:
        parser.error("--tag and --sums are required")
    try:
        text = render(args.tag, Path(args.sums).read_text(encoding="utf-8"), assets=args.assets)
    except (RenderError, OSError) as error:
        print(f"render-formula: {error}", file=sys.stderr)
        sys.exit(1)
    if args.out:
        write_atomic(args.out, text)
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
