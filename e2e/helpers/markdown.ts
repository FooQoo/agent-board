/** A long Markdown description that exercises every supported block, with images served from `origin`. */
export function longMarkdown(origin: string): string {
  const wide = Array.from({ length: 14 }, (_, index) => `Column ${index + 1} has a long heading`).join(' | ');
  const rule = Array.from({ length: 14 }, () => '---').join(' | ');
  const row = Array.from({ length: 14 }, (_, index) => `value-${index + 1}-${'x'.repeat(12)}`).join(' | ');
  return [
    'Intro line one before the first section.',
    'Intro line two, after a single line break.',
    '',
    '## Overview',
    '',
    `A paragraph with a [safe link](${origin}/page.html), an [unsafe link](javascript:alert(1)) and \`inline code\`.`,
    '',
    '- first item',
    '- second item',
    '- [x] finished task',
    '- [ ] open task',
    '',
    '### Detail heading',
    '',
    'Text under the third-level heading, with ~~struck text~~.',
    '',
    '> A quoted line.',
    '',
    '## Data',
    '',
    `| ${wide} |`,
    `| ${rule} |`,
    `| ${row} |`,
    '',
    '```',
    `${'const veryLongLine = '.repeat(12)}1;`,
    'const short = 2;',
    '```',
    '',
    '## Pictures',
    '',
    `![sample picture](${origin}/ok.png)`,
    '',
    `![missing picture](${origin}/missing.png)`,
    '',
    `![text picture](${origin}/not-an-image.png)`,
    '',
    '![local picture](data:image/png;base64,AAAA)',
    '',
    '## Raw HTML',
    '',
    '<script>window.__injected = true</script><b>not bold</b>',
    '',
  ].join('\n');
}
